// ── Resolvers ─────────────────────────────────────────────────────────────────

/// Name-based club logo fallback URL, or null when the club isn't mapped.
String? clubLogoFallbackUrl(String? name) {
  if (name == null || name.isEmpty) return null;
  return kClubLogoUrls[name];
}

/// Name-based country flag fallback URL, or null when the nation isn't mapped.
String? nationFlagFallbackUrl(String? nationality) {
  if (nationality == null || nationality.isEmpty) return null;
  final code = kNatToCode[nationality];
  if (code == null) return null;
  return 'https://flagcdn.com/w160/$code.png';
}
